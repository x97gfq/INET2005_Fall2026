<?php
// Assignment operators assign or update a variable's value
$total = 10;      // simple assignment
echo "Start: $total<br>";

$total += 5;      // same as $total = $total + 5
echo "After += 5: $total<br>";

$total -= 3;      // same as $total = $total - 3
echo "After -= 3: $total<br>";

$total *= 2;      // same as $total = $total * 2
echo "After *= 2: $total<br>";

$total /= 4;      // same as $total = $total / 4
echo "After /= 4: $total<br>";
?>
